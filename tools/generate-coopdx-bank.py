"""Regenerate the sm64coopdx extended-bank table used by the M64 exporter.

Usage: python tools/generate-coopdx-bank.py <path to sm64coopdx sound/sound_banks/30_extended.json>
then format libraries/m64export/src/coopdx_bank.c with the repository .clang-format.

Only sample indices, tunings, envelopes and note ranges are read; no audio is embedded. Samples
are referred to by their index in SM64's "instruments" sample bank; samples copied from other
sample banks (selected with "ifdef") are marked -1, because the exporter never maps to them.
"""
import json
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1] / "libraries" / "m64export"
catalog = json.loads((root / "catalog.json").read_text(encoding="utf-8"))
bank = json.loads(re.sub(r"//.*", "", Path(sys.argv[1]).read_text(encoding="utf-8")))
rates = {}

for name, rate in catalog["samples"].items():
    rates[int(name[:2], 16)] = rate


def sound(value):
    if value is None:
        return "{-1, 0}"

    if isinstance(value, dict) and "ifdef" in value:
        return "{-1, 0}"

    name = value if isinstance(value, str) else value["sample"]
    index = int(name[:2], 16)
    tuning = rates[index] / 32000 if isinstance(value, str) else value["tuning"]
    return "{%d, %.9g}" % (index, tuning)


lines = [
    "/* sm64coopdx sound bank 0x2A (sound/sound_banks/30_extended.json). Generated by",
    "   tools/generate-coopdx-bank.py. Metadata only. */",
    '#include "internal.h"',
    "const CoopdxInstrument coopdx_instruments[COOPDX_INSTRUMENTS] = {",
]
names = bank["instrument_list"]
assert len(names) == 204

for i, name in enumerate(names):
    if name is None:
        lines.append("    {0}, /* %d */" % i)
        continue

    inst = bank["instruments"][name]
    envelope = bank["envelopes"][inst["envelope"]]
    points = [p for p in envelope if isinstance(p, list)]
    sustained = 1 if points[-1][1] > 0 else 0
    lines.append(
        "    {1, %d, %d, %d, %d, %d, %s, %s, %s}, /* %d */"
        % (
            inst["release_rate"],
            points[0][0],
            sustained,
            inst.get("normal_range_lo", 0),
            inst.get("normal_range_hi", 127),
            sound(inst.get("sound_lo")),
            sound(inst.get("sound")),
            sound(inst.get("sound_hi")),
            i,
        )
    )

lines.append("};")
drums = bank["instruments"]["percussion"]
assert len(drums) == 64
lines.append("const CoopdxSound coopdx_drums[64] = {")

for i, drum in enumerate(drums):
    lines.append("    %s, /* %d */" % (sound(drum["sound"]), i))

lines.append("};")
(root / "src" / "coopdx_bank.c").write_text("\n".join(lines) + "\n", encoding="utf-8")
