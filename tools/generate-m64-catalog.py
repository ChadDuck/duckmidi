"""Regenerate the native library's tables from its reviewed metadata catalog.

Only names and numeric tuning/envelope metadata are used; no audio is embedded.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1] / "libraries" / "m64export"
catalog = json.loads((root / "catalog.json").read_text(encoding="utf-8"))
lines = ['/* Generated by tools/generate-m64-catalog.py. Metadata only. */', '#include "internal.h"']
for key, name in [("programs", "gm_programs"), ("drums", "gm_drums")]:
    rows = catalog[key]
    assert len(rows) == 128
    lines.append(f"const M64Instrument {name}[128] = {{")
    for i, row in enumerate(rows):
        assert row["sample"] in catalog["samples"]
        tuning = row.get("tuning", catalog["samples"][row["sample"]] / 32000)
        lines.append('    {"%s", %.14g, %d, %d, %d, %d}, /* %d */' % (
            row["sample"], tuning, row.get("release_rate", 10 if key == "drums" else 128),
            row.get("attack", 2), row.get("decay", 1), row.get("sustain", 29430), i))
    lines.append("};")
lines.append("const StockRegister stock_registers[] = {")
for family, samples in enumerate(catalog["register_families"]):
    for sample in samples:
        lines.append('    {"%s", %.14g, %d},' % (sample, catalog["samples"][sample]/32000, family))
lines += ["};", "const size_t stock_register_count = sizeof(stock_registers)/sizeof(*stock_registers);"]
(root / "src" / "catalog.c").write_text("\n".join(lines) + "\n", encoding="utf-8")
